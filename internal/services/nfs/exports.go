const exportsMarker = "# === This file is automatically generated by Sylve, don't edit! ==="

type Preview struct {
	Exports  string   `json:"exports"`
	Warnings []string `json:"warnings"`
}

type exportPlan struct {
	Preview
	filesystems  []nfsModels.ExportedFilesystem
	mappings     []nfsModels.MappingIdentity
	kerberosHash string
}

// PreviewExports validates the complete saved state against fresh ZFS/mount
// information. It never writes exports, changes ACLs or starts/stops daemons.
// It is not evidence that the native kernel has accepted an export policy.
func (s *Service) PreviewExports(ctx context.Context) (Preview, error) {
	policy, err := s.readPolicy(ctx)
	if err != nil {
		return Preview{}, err
	}
	plan, err := s.buildExportPlan(ctx, policy, nil, nil)
	return plan.Preview, err
}

func (s *Service) buildExportPlan(ctx context.Context, policy savedPolicy, known []*gzfs.Dataset, hints []nfsModels.ExportedFilesystem) (exportPlan, error) {
	config, err := normalizeConfig(policy.config)
	if err != nil {
		return exportPlan{}, err
	}
	shares := policy.shares
	enabled := make([]nfsModels.NFSShare, 0, len(shares))
	for _, share := range shares {
		if !share.Enabled {
			continue
		}
		share.NFSShareConfig, err = normalizeShare(share.NFSShareConfig)
		if err != nil {
			return exportPlan{}, err
		}
		enabled = append(enabled, share)
	}
	if err := validateClientConflicts(enabled); err != nil {
		return exportPlan{}, err
	}
	kerberosHash, err := s.kerberosState(ctx, config, enabled)
	if err != nil {
		return exportPlan{}, err
	}
	warnings := []string{"Preview only: no host changes were made.", "AUTH_SYS trusts client-supplied numeric identities; filesystem permissions are not changed."}
	if len(enabled) == 0 {
		return exportPlan{Preview: Preview{Exports: exportsMarker + "\n", Warnings: append(warnings, "No shares are enabled.")}}, nil
	}
	byGUID := make(map[string]*gzfs.Dataset, len(known)+len(hints))
	for _, filesystem := range hints {
		byGUID[filesystem.GUID] = &gzfs.Dataset{GUID: filesystem.GUID, Name: filesystem.Name}
	}
	for _, dataset := range known {
		byGUID[dataset.GUID] = dataset
	}
	discovered := false
	for _, share := range enabled {
		if byGUID[share.Dataset] == nil {
			datasets, err := s.discover(ctx)
			if err != nil {
				return exportPlan{}, err
			}
			clear(byGUID)
			for _, dataset := range datasets {
				byGUID[dataset.GUID] = dataset
			}
			discovered = true
			break
		}
	}
	if !discovered {
		// Hints from a prior apply or pre-save validation are not authority.
		// Re-read just the selected names after withdrawal, including GUIDs and
		// inherited properties, before publishing any grants.
		names := []string{}
		for _, share := range enabled {
			name := byGUID[share.Dataset].Name
			if !slices.Contains(names, name) {
				names = append(names, name)
			}
		}
		datasets, err := s.inspectDatasets(ctx, names)
		if err != nil {
			return exportPlan{}, err
		}
		clear(byGUID)
		for _, dataset := range datasets {
			if dataset == nil || !validGUID(dataset.GUID) || byGUID[dataset.GUID] != nil {
				return exportPlan{}, fmt.Errorf("ZFS returned an incomplete or ambiguous filesystem identity")
			}
			byGUID[dataset.GUID] = dataset
		}
	}
	resolved := make(map[string]*gzfs.Dataset)
	for _, share := range enabled {
		if resolved[share.Dataset] != nil {
			continue
		}
		dataset := byGUID[share.Dataset]
		if err := s.checkDataset(dataset, policy.pools); err != nil {
			return exportPlan{}, conflict("dataset", fmt.Sprintf("Share %d: %s", share.ID, err))
		}
		resolved[share.Dataset] = dataset
	}
	mappings, identities, err := s.resolveMappings(ctx, enabled)
	if err != nil {
		return exportPlan{}, err
	}
	mounts := make([]nfsModels.ExportedFilesystem, 0, len(resolved))
	for _, dataset := range resolved {
		mounts = append(mounts, nfsModels.ExportedFilesystem{GUID: dataset.GUID, Name: dataset.Name, Mountpoint: dataset.Mountpoint})
	}
	slices.SortFunc(mounts, func(a, b nfsModels.ExportedFilesystem) int { return strings.Compare(a.Name, b.Name) })
	exports := renderExports(config.Protocol, enabled, resolved, mappings)
	if len(exports) > 1024*1024 {
		return exportPlan{}, conflict("dataset", "Generated NFS exports exceed 1 MiB.")
	}
	return exportPlan{Preview: Preview{Exports: exports, Warnings: warnings}, filesystems: mounts, mappings: identities, kerberosHash: kerberosHash}, nil
}

// mountd decodes directory names with strunvis(3). Octal-encode whitespace,
// backslashes and punctuation instead of using shell quoting or raw interpolation.
func exportsPath(path string) string {
	var out strings.Builder
	for _, value := range []byte(path) {
		if value >= 'a' && value <= 'z' || value >= 'A' && value <= 'Z' || value >= '0' && value <= '9' || strings.ContainsRune("/._-", rune(value)) {
			out.WriteByte(value)
		} else {
			fmt.Fprintf(&out, "\\%03o", value)
		}
	}
	return out.String()
}

func clientSuffix(client string) string {
	if client == "" {
		return ""
	}
	if strings.Contains(client, "/") {
		return " -network=" + client
	}
	return " " + client
}

func renderExports(protocol string, shares []nfsModels.NFSShare, datasets map[string]*gzfs.Dataset, mappings map[uint]string) string {
	shares = slices.Clone(shares)
	slices.SortFunc(shares, func(a, b nfsModels.NFSShare) int {
		if diff := strings.Compare(datasets[a.Dataset].Mountpoint, datasets[b.Dataset].Mountpoint); diff != 0 {
			return diff
		}
		return cmp.Compare(a.ID, b.ID)
	})
	var out strings.Builder
	out.WriteString(exportsMarker + "\n\n")
	if protocol != "v3" {
		// The NFSv4 namespace root is not a filesystem export. Access remains
		// controlled by the individual share rules below.
		rootSecurity := []string{}
		for _, flavor := range securityFlavors {
			if slices.ContainsFunc(shares, func(share nfsModels.NFSShare) bool { return slices.Contains(shareSecurity(share), flavor) }) {
				rootSecurity = append(rootSecurity, flavor)
			}
		}
		out.WriteString("V4: / -sec=" + strings.Join(rootSecurity, ":") + "\n\n")
	}
	for _, share := range shares {
		fmt.Fprintf(&out, "# Share %d\n", share.ID)
		options := " -sec=" + strings.Join(shareSecurity(share), ":") + mappings[share.ID]
		if share.AllDirs {
			options += " -alldirs"
		}
		if share.ReadOnly {
			options += " -ro"
		}
		clients := share.Clients
		if share.Everyone {
			clients = []string{""}
		}
		for _, client := range clients {
			fmt.Fprintf(&out, "%s%s%s\n", exportsPath(datasets[share.Dataset].Mountpoint), options, clientSuffix(client))
		}
		out.WriteByte('\n')
	}
	return out.String()
}
