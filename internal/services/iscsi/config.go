const configMarker = "# === This file is automatically generated by Sylve, don't edit! ==="

var configPath = "/etc/iscsi.conf"
var targetConfigPath = "/etc/ctl.conf"

func SetConfigPath(path string) func() {
	previous := configPath
	configPath = path
	return func() { configPath = previous }
}

func SetTargetConfigPath(path string) func() {
	previous := targetConfigPath
	targetConfigPath = path
	return func() { targetConfigPath = previous }
}

func (s *Service) GenerateConfig() (string, error) {
	s.mutationMu.Lock()
	defer s.mutationMu.Unlock()

	return s.generateConfig()
}

func (s *Service) generateConfig() (string, error) {
	var initiators []iscsiModels.ISCSIInitiator
	if err := s.DB.Find(&initiators).Error; err != nil {
		return "", fmt.Errorf("failed_to_load_initiators: %w", err)
	}

	var b strings.Builder
	b.WriteString(configMarker + "\n\n")

	for _, ini := range initiators {
		if ini.Nickname == "" {
			return "", invalidRequest("nickname_required")
		}
		if err := validateBareConfigToken(ini.Nickname, "nickname", maxNicknameLength); err != nil {
			return "", err
		}
		targetAddress, err := normalizeInitiatorTargetAddress(ini.TargetAddress)
		if err != nil {
			return "", err
		}
		if ini.TargetName == "" {
			return "", invalidRequest("target_name_required")
		}
		if err := validateBareConfigToken(ini.TargetName, "target_name", maxISCSINameLength); err != nil {
			return "", err
		}
		if ini.InitiatorName != "" {
			if err := validateBareConfigToken(ini.InitiatorName, "initiator_name", maxISCSINameLength); err != nil {
				return "", err
			}
		}
		authMethod := strings.TrimSpace(ini.AuthMethod)
		if authMethod == "" {
			authMethod = "None"
		}
		if err := validateAuthMethod(authMethod, ini.CHAPName, ini.CHAPSecret, ini.TgtCHAPName, ini.TgtCHAPSecret); err != nil {
			return "", err
		}

		b.WriteString(fmt.Sprintf("%s {\n", ini.Nickname))
		b.WriteString(fmt.Sprintf("\ttargetaddress\t= %s;\n", targetAddress))
		b.WriteString(fmt.Sprintf("\ttargetname\t= %s;\n", ini.TargetName))
		if ini.InitiatorName != "" {
			b.WriteString(fmt.Sprintf("\tinitiatorname\t= %s;\n", ini.InitiatorName))
		}

		switch authMethod {
		case "CHAP":
			b.WriteString("\tauthmethod\t= CHAP;\n")
			b.WriteString(fmt.Sprintf("\tchapiname\t= %s;\n", nativeQuote(ini.CHAPName)))
			b.WriteString(fmt.Sprintf("\tchapsecret\t= %s;\n", nativeQuote(ini.CHAPSecret)))
		case "MutualCHAP":
			b.WriteString("\tauthmethod\t= CHAP;\n")
			b.WriteString(fmt.Sprintf("\tchapiname\t= %s;\n", nativeQuote(ini.CHAPName)))
			b.WriteString(fmt.Sprintf("\tchapsecret\t= %s;\n", nativeQuote(ini.CHAPSecret)))
			b.WriteString(fmt.Sprintf("\ttgtChapName\t= %s;\n", nativeQuote(ini.TgtCHAPName)))
			b.WriteString(fmt.Sprintf("\ttgtChapSecret\t= %s;\n", nativeQuote(ini.TgtCHAPSecret)))
		}

		b.WriteString("}\n\n")
	}

	return b.String(), nil
}

func (s *Service) WriteConfig(reload bool) error {
	s.mutationMu.Lock()
	defer s.mutationMu.Unlock()

	return s.writeConfig(reload)
}

func (s *Service) writeConfig(reload bool) error {
	cfg, err := s.generateConfig()
	if err != nil {
		return err
	}

	if err := utils.AtomicWriteFile(s.initiatorPath(), []byte(cfg), 0600); err != nil {
		logger.L.Error().Err(err).Msg("failed to write iSCSI initiator config")
		return applyFailed("failed_to_write_iscsi_config", err)
	}

	if !reload {
		return nil
	}

	if _, err := s.runInitiatorCommand("-Aa"); err != nil {
		logger.L.Error().Err(err).Msg("failed to add configured iSCSI initiator sessions")
		return applyFailed("failed_to_add_iscsi_sessions", err)
	}

	return nil
}

func (s *Service) GenerateTargetConfig() (string, error) {
	s.mutationMu.Lock()
	defer s.mutationMu.Unlock()

	ctx, cancel := s.targetContext()
	defer cancel()
	return s.generateTargetConfigContext(ctx)
}

func (s *Service) generateTargetConfigContext(ctx context.Context) (string, error) {
	var targets []iscsiModels.ISCSITarget
	if err := s.DB.Preload("Portals").Preload("LUNs").Order("id").Find(&targets).Error; err != nil {
		return "", fmt.Errorf("failed_to_load_targets: %w", err)
	}
	endpoints, attachments, err := s.collectPortalEndpointsContext(ctx, targets)
	if err != nil {
		return "", err
	}

	var b strings.Builder
	b.WriteString(configMarker + "\n\n")
	usedZVols := make(map[string]struct{})
	if s.runtime != nil && s.runtime.pidFile != "" {
		if err := validateNativeQuotedValue(s.runtime.pidFile, "pidfile"); err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "pidfile %s\n\n", nativeQuote(s.runtime.pidFile))
	}
	for _, endpoint := range endpoints {
		fmt.Fprintf(&b, "portal-group %s {\n\tdiscovery-auth-group no-authentication\n\tlisten %s\n}\n\n", s.groupName(endpoint), nativeQuote(endpoint.listen()))
	}
	for _, target := range targets {
		if len(attachments[target.ID]) == 0 {
			b.WriteString("portal-group pg-unbound {\n}\n\n")
			break
		}
	}

	for _, tgt := range targets {
		if tgt.TargetName == "" {
			return "", invalidRequest("target_name_required")
		}
		if err := validateBareConfigToken(tgt.TargetName, "target_name", maxISCSINameLength); err != nil {
			return "", err
		}
		if err := validateNativeQuotedValue(tgt.Alias, "alias"); err != nil {
			return "", err
		}
		authMethod := strings.TrimSpace(tgt.AuthMethod)
		if authMethod == "" {
			authMethod = "None"
		}
		if err := validateTargetAuthMethod(authMethod, tgt.CHAPName, tgt.CHAPSecret, tgt.MutualCHAPName, tgt.MutualCHAPSecret); err != nil {
			return "", err
		}

		if authMethod == "CHAP" || authMethod == "MutualCHAP" {
			b.WriteString(fmt.Sprintf("auth-group ag-%d {\n", tgt.ID))
			if authMethod == "MutualCHAP" {
				b.WriteString(fmt.Sprintf("\tchap-mutual %s %s %s %s\n",
					nativeQuote(tgt.CHAPName), nativeQuote(tgt.CHAPSecret), nativeQuote(tgt.MutualCHAPName), nativeQuote(tgt.MutualCHAPSecret)))
			} else {
				b.WriteString(fmt.Sprintf("\tchap %s %s\n", nativeQuote(tgt.CHAPName), nativeQuote(tgt.CHAPSecret)))
			}
			b.WriteString("}\n\n")
		}

		b.WriteString(fmt.Sprintf("target %s {\n", nativeQuote(tgt.TargetName)))
		if tgt.Alias != "" {
			b.WriteString(fmt.Sprintf("\talias %s\n", nativeQuote(tgt.Alias)))
		}
		if len(attachments[tgt.ID]) == 0 {
			b.WriteString("\tportal-group pg-unbound\n")
		}
		for _, endpoint := range attachments[tgt.ID] {
			fmt.Fprintf(&b, "\tportal-group %s\n", s.groupName(endpoint))
		}
		if authMethod == "CHAP" || authMethod == "MutualCHAP" {
			b.WriteString(fmt.Sprintf("\tauth-group ag-%d\n", tgt.ID))
		} else {
			b.WriteString("\tauth-group no-authentication\n")
		}
		sort.Slice(tgt.LUNs, func(i, j int) bool { return tgt.LUNs[i].LUNNumber < tgt.LUNs[j].LUNNumber })
		for _, lun := range tgt.LUNs {
			if lun.LUNNumber < 0 {
				return "", invalidRequest("lun_number_must_be_non_negative")
			}
			if lun.LUNNumber > maxTargetLUNNumber {
				return "", invalidRequest("lun_number_must_be_between_0_and_1023")
			}
			if err := validateZVol(lun.ZVol); err != nil {
				return "", err
			}
			if _, exists := usedZVols[lun.ZVol]; exists {
				return "", resourceConflict("zvol_already_in_use", nil)
			}
			usedZVols[lun.ZVol] = struct{}{}
			if _, err := s.statBacking("/dev/zvol/" + lun.ZVol); err != nil {
				return "", invalidRequest("zvol_backing_not_available")
			}

			b.WriteString(fmt.Sprintf("\tlun %d {\n", lun.LUNNumber))
			b.WriteString(fmt.Sprintf("\t\tpath %s\n", nativeQuote("/dev/zvol/"+lun.ZVol)))
			b.WriteString("\t}\n")
		}
		b.WriteString("}\n\n")
	}

	return b.String(), nil
}

