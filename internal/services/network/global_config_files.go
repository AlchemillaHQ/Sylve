const (
	globalDNSBlockBegin   = "# BEGIN SYLVE NETWORK DNS"
	globalDNSBlockEnd     = "# END SYLVE NETWORK DNS"
	globalHostsBlockBegin = "# BEGIN SYLVE HOST ALIASES"
	globalHostsBlockEnd   = "# END SYLVE HOST ALIASES"
)

type globalConfigRuntimeOperations struct {
	resolvconfPath string
	resolverPath   string
	hostsPath      string
	writeFile      func(string, []byte, os.FileMode) error
	removeFile     func(string) error
	runCommand     func(context.Context, string, ...string) (string, error)
}

func (s *Service) globalRuntime() globalConfigRuntimeOperations {
	runtime := s.globalConfigRuntime
	if runtime.resolvconfPath == "" {
		runtime.resolvconfPath = "/etc/resolvconf.conf"
	}
	if runtime.resolverPath == "" {
		runtime.resolverPath = "/etc/resolv.conf"
	}
	if runtime.hostsPath == "" {
		runtime.hostsPath = "/etc/hosts"
	}
	if runtime.writeFile == nil {
		runtime.writeFile = utils.AtomicWriteFile
	}
	if runtime.removeFile == nil {
		runtime.removeFile = os.Remove
	}
	if runtime.runCommand == nil {
		runtime.runCommand = utils.RunCommandWithContext
	}
	return runtime
}

type globalFileSnapshot struct {
	path   string
	data   []byte
	mode   os.FileMode
	exists bool
}

func snapshotGlobalFile(path string) (globalFileSnapshot, error) {
	snapshot := globalFileSnapshot{path: path, mode: 0o644}
	info, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return snapshot, nil
	}
	if err != nil {
		return snapshot, err
	}
	// Do not replace symlinks, special files, or unexpectedly large host files.
	if !info.Mode().IsRegular() || info.Size() > 4*1024*1024 {
		return snapshot, conflictingGlobalConfig("global_config_file_not_regular")
	}
	snapshot.data, err = os.ReadFile(path)
	snapshot.mode, snapshot.exists = info.Mode().Perm(), true
	return snapshot, err
}

type globalFileUpdate struct {
	before  globalFileSnapshot
	data    []byte
	touched bool
}

type globalConfigApplication struct {
	runtime  globalConfigRuntimeOperations
	files    []globalFileUpdate
	resolver *globalFileSnapshot
	config   networkModels.GlobalConfig
	dnsRan   bool
}

func globalDNSManaged(config networkModels.GlobalConfig) bool {
	return config.DNSMode == "manual" || config.SearchDomainsOverride
}

func (s *Service) prepareGlobalConfig(current, candidate networkModels.GlobalConfig, force bool) (*globalConfigApplication, error) {
	application := &globalConfigApplication{runtime: s.globalRuntime(), config: candidate}
	dnsChanged := current.DNSMode != candidate.DNSMode || !slices.Equal(current.DNSServers, candidate.DNSServers) ||
		current.SearchDomainsOverride != candidate.SearchDomainsOverride || !slices.Equal(current.SearchDomains, candidate.SearchDomains) ||
		(force && globalDNSManaged(candidate))
	if dnsChanged {
		resolver, err := snapshotGlobalFile(application.runtime.resolverPath)
		if err != nil {
			return nil, err
		}
		if globalDNSManaged(candidate) && len(resolver.data) > 0 && !bytes.HasPrefix(resolver.data, []byte("# Generated by resolvconf\n")) {
			return nil, conflictingGlobalConfig("global_resolver_not_resolvconf_managed")
		}
		configuration, err := snapshotGlobalFile(application.runtime.resolvconfPath)
		if err != nil {
			return nil, err
		}
		block := ""
		if globalDNSManaged(candidate) {
			block = renderGlobalDNSBlock(candidate, application.runtime.resolverPath, resolverExtras(resolver.data))
		}
		data, err := replaceGlobalBlock(configuration.data, globalDNSBlockBegin, globalDNSBlockEnd, block)
		if err != nil {
			return nil, err
		}
		application.files = append(application.files, globalFileUpdate{before: configuration, data: data})
		application.resolver = &resolver
	}
	if !reflect.DeepEqual(current.HostAliases, candidate.HostAliases) || (force && len(candidate.HostAliases) > 0) {
		hosts, err := snapshotGlobalFile(application.runtime.hostsPath)
		if err != nil {
			return nil, err
		}
		unmanaged, err := replaceGlobalBlock(hosts.data, globalHostsBlockBegin, globalHostsBlockEnd, "")
		if err != nil {
			return nil, err
		}
		if err := validateUnmanagedHostAliases(unmanaged, candidate.HostAliases); err != nil {
			return nil, err
		}
		var entries strings.Builder
		for _, alias := range candidate.HostAliases {
			fmt.Fprintf(&entries, "%s\t%s\n", alias.Address, strings.Join(append([]string{alias.Hostname}, alias.Aliases...), " "))
		}
		data, err := replaceGlobalBlock(hosts.data, globalHostsBlockBegin, globalHostsBlockEnd, entries.String())
		if err != nil {
			return nil, err
		}
		application.files = append(application.files, globalFileUpdate{before: hosts, data: data})
	}
	return application, nil
}

func (a *globalConfigApplication) apply(ctx context.Context) error {
	for i := range a.files {
		file := &a.files[i]
		if err := ctx.Err(); err != nil {
			return err
		}
		if bytes.Equal(file.before.data, file.data) {
			continue
		}
		file.touched = true
		if err := a.setFile(file.before.path, file.data, file.before.mode, len(file.data) > 0); err != nil {
			return fmt.Errorf("write network global configuration: %w", err)
		}
	}
	if a.resolver == nil {
		return ctx.Err()
	}
	a.dnsRan = true
	commandCtx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	if _, err := a.runtime.runCommand(commandCtx, "/sbin/resolvconf", "-u"); err != nil {
		return fmt.Errorf("apply resolver configuration: %w", err)
	}
	data, err := os.ReadFile(a.runtime.resolverPath)
	if err != nil {
		return fmt.Errorf("read applied resolver configuration: %w", err)
	}
	servers, domains := parseGlobalResolver(data)
	if a.config.DNSMode == "manual" && !slices.Equal(servers, a.config.DNSServers) {
		return errors.New("global_dns_apply_verification_failed")
	}
	if a.config.SearchDomainsOverride && !slices.Equal(domains, a.config.SearchDomains) {
		return errors.New("global_search_domain_apply_verification_failed")
	}
	// resolvconf regenerates the file. Retain unrelated comments/options even on
	// release; future DHCP/RA updates are once again entirely OS-owned.
	if !globalDNSManaged(a.config) {
		for _, line := range strings.Split(resolverExtras(a.resolver.data), "\n") {
			if line != "" && !slices.Contains(strings.Split(string(data), "\n"), line) {
				data = append(data, []byte(line+"\n")...)
			}
		}
		if err := a.runtime.writeFile(a.runtime.resolverPath, data, a.resolver.mode); err != nil {
			return err
		}
	}
	return ctx.Err()
}

func (a *globalConfigApplication) setFile(path string, data []byte, mode os.FileMode, exists bool) error {
	if exists {
		return a.runtime.writeFile(path, data, mode)
	}
	err := a.runtime.removeFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	return err
}

func (a *globalConfigApplication) restore() error {
	var failures []error
	for _, file := range a.files {
		if file.touched {
			if err := a.setFile(file.before.path, file.before.data, file.before.mode, file.before.exists); err != nil {
				failures = append(failures, fmt.Errorf("restore %s: %w", file.before.path, err))
			}
		}
	}
	if a.dnsRan {
		ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		_, err := a.runtime.runCommand(ctx, "/sbin/resolvconf", "-u")
		cancel()
		if err != nil {
			failures = append(failures, fmt.Errorf("restore resolver subscribers: %w", err))
		}
		if err := a.setFile(a.resolver.path, a.resolver.data, a.resolver.mode, a.resolver.exists); err != nil {
			failures = append(failures, fmt.Errorf("restore resolver file: %w", err))
		}
	}
	return errors.Join(failures...)
}

func renderGlobalDNSBlock(config networkModels.GlobalConfig, resolverPath, extras string) string {
	var block strings.Builder
	// resolvconf also configures caching DNS services. Override libc's exported
	// inputs only, so host settings do not change those services' upstreams.
	// FreeBSD sources non-executable subscribers; $0 then remains resolvconf
	// and its script variable identifies the subscriber instead.
	block.WriteString("case \"${script:-$0}\" in\n*/libc|libc)\n")
	fmt.Fprintf(&block, "resolv_conf='%s'\nresolv_conf_passthrough=\"NO\"\nresolv_conf_mv=\"YES\"\n", strings.ReplaceAll(resolverPath, "'", "'\\''"))
	if extras != "" {
		// resolvconf.conf is sourced by sh. Never interpolate file content as code.
		fmt.Fprintf(&block, "resolv_conf_head='%s'\nresolv_conf_tail=\"\"\n", strings.ReplaceAll(extras, "'", "'\\''"))
	}
	if config.DNSMode == "manual" {
		fmt.Fprintf(&block, "prepend_nameservers=\"%s\"\nappend_nameservers=\"\"\nNAMESERVERS=\"\"\nLOCALNAMESERVERS=\"\"\nresolv_conf_local_only=\"NO\"\n", strings.Join(config.DNSServers, " "))
	}
	if config.SearchDomainsOverride {
		fmt.Fprintf(&block, "domain=\"\"\nDOMAIN=\"\"\nSEARCH=\"\"\nprepend_search=\"%s\"\nappend_search=\"\"\n", strings.Join(config.SearchDomains, " "))
	}
	block.WriteString(";;\nesac\n")
	return block.String()
}

func replaceGlobalBlock(data []byte, begin, end, block string) ([]byte, error) {
	var preserved strings.Builder
	inside, found := false, false
	for _, line := range strings.SplitAfter(string(data), "\n") {
		switch strings.TrimSpace(line) {
		case begin:
			if inside || found {
				return nil, conflictingGlobalConfig("global_config_managed_block_invalid")
			}
			inside, found = true, true
		case end:
			if !inside {
				return nil, conflictingGlobalConfig("global_config_managed_block_invalid")
			}
			inside = false
		default:
			if !inside {
				preserved.WriteString(line)
			}
		}
	}
	if inside {
		return nil, conflictingGlobalConfig("global_config_managed_block_invalid")
	}
	if block != "" {
		if preserved.Len() > 0 && !strings.HasSuffix(preserved.String(), "\n") {
			preserved.WriteByte('\n')
		}
		fmt.Fprintf(&preserved, "%s\n%s%s\n", begin, block, end)
	}
	return []byte(preserved.String()), nil
}

func resolverExtras(data []byte) string {
	var lines []string
	for _, line := range strings.Split(string(data), "\n") {
		fields := strings.Fields(line)
		if len(fields) == 0 || line == "# Generated by resolvconf" || fields[0] == "nameserver" || fields[0] == "search" || fields[0] == "domain" {
			continue
		}
		if !slices.Contains(lines, line) {
			lines = append(lines, line)
		}
	}
	return strings.Join(lines, "\n")
}

func parseGlobalResolver(data []byte) ([]string, []string) {
	servers, domains := []string{}, []string{}
	for _, line := range strings.Split(string(data), "\n") {
		line, _, _ = strings.Cut(line, "#")
		fields := strings.Fields(line)
		if len(fields) < 2 {
			continue
		}
		switch fields[0] {
		case "nameserver":
			server := fields[1]
			if address, err := netip.ParseAddr(server); err == nil {
				server = address.Unmap().String()
			}
			servers = append(servers, server)
		case "search":
			domains = append([]string{}, fields[1:]...)
		case "domain":
			domains = []string{fields[1]}
		}
	}
	return servers, domains
}

func validateUnmanagedHostAliases(data []byte, aliases []networkModels.HostAlias) error {
	names := map[string]string{}
	for _, alias := range aliases {
		address, _ := netip.ParseAddr(alias.Address)
		for _, name := range append([]string{alias.Hostname}, alias.Aliases...) {
			names[fmt.Sprintf("%t/%s", address.Is6(), name)] = alias.Address
		}
	}
	for _, line := range strings.Split(string(data), "\n") {
		line, _, _ = strings.Cut(line, "#")
		fields := strings.Fields(line)
		if len(fields) < 2 {
			continue
		}
		address, err := netip.ParseAddr(fields[0])
		if err != nil {
			continue
		}
		for _, name := range fields[1:] {
			key := fmt.Sprintf("%t/%s", address.Unmap().Is6(), strings.ToLower(name))
			if desired, ok := names[key]; ok && desired != address.Unmap().String() {
				return conflictingGlobalConfig("global_host_alias_conflicts_with_unmanaged_entry")
			}
		}
	}
	return nil
}
