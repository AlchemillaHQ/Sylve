func TestGlobalConfigSaveReapplyAndRelease(t *testing.T) {
	service := newGlobalConfigServiceForTest(t)
	runtime := service.globalRuntime()
	configBefore, hostsBefore := readGlobalTestFile(t, runtime.resolvconfPath), readGlobalTestFile(t, runtime.hostsPath)
	request := globalTestRequest(0)
	if err := service.UpdateGlobalConfig(t.Context(), request); err != nil {
		t.Fatal(err)
	}
	state, err := service.GetGlobalConfig(t.Context())
	if err != nil || state.Revision != 1 || !slices.Equal(state.EffectiveDNSServers, request.DNSServers) || !slices.Equal(state.EffectiveSearchDomains, []string{"lan"}) {
		t.Fatalf("saved state = %+v, %v", state, err)
	}
	for _, path := range []string{runtime.resolvconfPath, runtime.resolverPath, runtime.hostsPath} {
		info, err := os.Stat(path)
		if err != nil || info.Mode().Perm() != 0o640 {
			t.Fatalf("mode not preserved for %s: %v %v", path, info, err)
		}
	}
	if !strings.Contains(readGlobalTestFile(t, runtime.hostsPath), hostsBefore) || !strings.Contains(readGlobalTestFile(t, runtime.resolverPath), "# Keep this comment") {
		t.Fatal("unrelated file content lost")
	}
	// Model a reboot/OS refresh: saved settings must be reapplied, not reimported.
	writeGlobalTestFile(t, runtime.resolvconfPath, configBefore)
	writeGlobalTestFile(t, runtime.hostsPath, hostsBefore)
	if err := service.ReconcileGlobalConfig(t.Context()); err != nil {
		t.Fatal(err)
	}
	if strings.Count(readGlobalTestFile(t, runtime.hostsPath), globalHostsBlockBegin) != 1 {
		t.Fatal("reapply duplicated or lost the hosts block")
	}
	one := uint64(1)
	if err := service.UpdateGlobalConfig(t.Context(), networkServiceInterfaces.UpdateGlobalConfigRequest{DNSMode: "os", ExpectedRevision: &one}); err != nil {
		t.Fatal(err)
	}
	if got := readGlobalTestFile(t, runtime.resolvconfPath); got != configBefore {
		t.Fatalf("resolvconf ownership not released: %q", got)
	}
	if got := readGlobalTestFile(t, runtime.hostsPath); got != hostsBefore {
		t.Fatalf("unmanaged hosts not preserved on release: %q", got)
	}
	state, err = service.GetGlobalConfig(t.Context())
	if err != nil || state.DNSMode != "os" || state.Revision != 2 || state.EffectiveDNSServers[0] != "192.0.2.1" {
		t.Fatalf("released state = %+v %v", state, err)
	}
}

