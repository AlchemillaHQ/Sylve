func TestGlobalConfigFailuresRestoreFilesAndDatabase(t *testing.T) {
	for _, failure := range []string{"hosts write", "resolvconf", "verification", "database save", "database commit", "cancellation"} {
		t.Run(failure, func(t *testing.T) {
			service := newGlobalConfigServiceForTest(t)
			runtime := service.globalRuntime()
			before := map[string]string{}
			for _, path := range []string{runtime.resolvconfPath, runtime.resolverPath, runtime.hostsPath} {
				before[path] = readGlobalTestFile(t, path)
			}
			ctx, cancel := context.WithCancel(t.Context())
			defer cancel()
			switch failure {
			case "hosts write":
				service.globalConfigRuntime.writeFile = func(path string, data []byte, mode os.FileMode) error {
					if path == runtime.hostsPath && strings.Contains(string(data), globalHostsBlockBegin) {
						return errors.New("write failed")
					}
					return utils.AtomicWriteFile(path, data, mode)
				}
			case "resolvconf", "verification", "cancellation":
				calls := 0
				service.globalConfigRuntime.runCommand = func(commandCtx context.Context, command string, args ...string) (string, error) {
					calls++
					if calls > 1 {
						if commandCtx.Err() != nil {
							t.Fatal("recovery reused a canceled context")
						}
						return runtime.runCommand(commandCtx, command, args...)
					}
					writeGlobalTestFile(t, runtime.resolverPath, "# Generated by resolvconf\nnameserver 203.0.113.1\n")
					if failure == "resolvconf" {
						return "", errors.New("subscriber failed")
					}
					if failure == "cancellation" {
						cancel()
						return "", ctx.Err()
					}
					return "", nil
				}
			case "database save":
				service.DB.Callback().Create().Before("gorm:create").Register("fail_global_save", func(tx *gorm.DB) { tx.AddError(errors.New("database failed")) })
			case "database commit":
				service.DB.Exec("PRAGMA foreign_keys = ON")
				service.DB.Exec("CREATE TABLE global_commit_guard (parent INTEGER REFERENCES global_configs(id) DEFERRABLE INITIALLY DEFERRED)")
				service.DB.Exec("CREATE TRIGGER fail_global_commit AFTER INSERT ON global_configs BEGIN INSERT INTO global_commit_guard VALUES (999); END")
			}
			if err := service.UpdateGlobalConfig(ctx, globalTestRequest(0)); err == nil {
				t.Fatal("failure was reported as success")
			}
			for path, want := range before {
				if got := readGlobalTestFile(t, path); got != want {
					t.Fatalf("%s not restored: %q != %q", path, got, want)
				}
			}
			config, err := loadGlobalConfig(service.DB)
			if err != nil || config.Revision != 0 || config.DNSMode != "os" {
				t.Fatalf("failed candidate persisted: %+v %v", config, err)
			}
		})
	}
}

