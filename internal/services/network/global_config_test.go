func testGlobalConfigNativeResolvconfLifecycle(t *testing.T, subscriberMode os.FileMode) {
	t.Helper()
	service := newGlobalConfigServiceForTest(t)
	runtime := service.globalRuntime()
	directory := filepath.Dir(runtime.resolverPath)
	libexec, vardir := filepath.Join(directory, "libexec"), filepath.Join(directory, "state")
	for _, path := range []string{libexec, vardir} {
		if err := os.MkdirAll(path, 0o700); err != nil {
			t.Fatal(err)
		}
	}
	script := filepath.Join(directory, "resolvconf")
	for source, destination := range map[string]string{"/sbin/resolvconf": script, "/libexec/resolvconf/libc": filepath.Join(libexec, "libc")} {
		data, err := os.ReadFile(source)
		if err != nil {
			t.Skip("native openresolv is unavailable")
		}
		text := string(data)
		for from, to := range map[string]string{
			"SYSCONFDIR=/etc":                "SYSCONFDIR=" + directory,
			"LIBEXECDIR=/libexec/resolvconf": "LIBEXECDIR=" + libexec,
			"VARDIR=/var/run/resolvconf":     "VARDIR=" + vardir,
		} {
			if !strings.Contains(text, from) {
				t.Skip("unsupported native openresolv layout")
			}
			text = strings.ReplaceAll(text, from, to)
		}
		text = strings.ReplaceAll(text, "/sbin/resolvconf", script)
		text = strings.ReplaceAll(text, "/etc/resolv.conf", runtime.resolverPath)
		text = strings.ReplaceAll(text, "RCDIR=/etc/rc.d", "RCDIR="+directory)
		lines := strings.Split(text, "\n")
		for i, line := range lines {
			if strings.HasPrefix(line, "RESTARTCMD=") {
				lines[i] = "RESTARTCMD=\":\""
			}
		}
		mode := os.FileMode(0o700)
		if source == "/libexec/resolvconf/libc" {
			mode = subscriberMode
		}
		if err := os.WriteFile(destination, []byte(strings.Join(lines, "\n")), mode); err != nil {
			t.Fatal(err)
		}
	}
	writeGlobalTestFile(t, runtime.resolvconfPath, fmt.Sprintf("resolv_conf='%s'\nlibc_restart=':'\n", runtime.resolverPath))
	baseline := readGlobalTestFile(t, runtime.resolvconfPath)
	// Let native resolvconf select its state layout (interfaces on FreeBSD 15,
	// keys on newer versions) rather than writing subscriber inputs directly.
	setResolverInput := func(name, content string) {
		t.Helper()
		if _, err := utils.RunCommandWithInputContext(t.Context(), content, script, "-a", name); err != nil {
			t.Fatal(err)
		}
	}
	resolverBefore := readGlobalTestFile(t, runtime.resolverPath)
	setResolverInput("bridge0", "search lan\nnameserver 192.0.2.1\noptions edns0\n")
	setResolverInput("bridge0:slaac", "nameserver 2001:db8::1\n")
	unsafePath := filepath.Join(directory, "must-not-exist")
	writeGlobalTestFile(t, runtime.resolverPath, resolverBefore+"# Someone's literal $(touch "+unsafePath+") comment\n")
	service.globalConfigRuntime.runCommand = func(ctx context.Context, command string, args ...string) (string, error) {
		if command == "/sbin/resolvconf" {
			return utils.RunCommandWithContext(ctx, script, args...)
		}
		return runtime.runCommand(ctx, command, args...)
	}
	request := globalTestRequest(0)
	request.SearchDomainsOverride, request.SearchDomains = true, []string{"ad.sylve.test"}
	for step := range 6 {
		if step == 1 {
			request.SearchDomains = nil
		}
		if step == 2 {
			request.SearchDomainsOverride = false
		}
		if step == 3 {
			request.DNSMode, request.DNSServers = "os", nil
			request.SearchDomainsOverride, request.SearchDomains = true, []string{"lab.test"}
		}
		if step == 4 {
			request.SearchDomains = nil
		}
		if step == 5 {
			request.DNSMode, request.DNSServers = "os", nil
			request.SearchDomainsOverride = false
		}
		if err := service.UpdateGlobalConfig(t.Context(), request); err != nil {
			t.Fatalf("native step %d: %v", step, err)
		}
		state, err := service.GetGlobalConfig(t.Context())
		if err != nil {
			t.Fatal(err)
		}
		request.ExpectedRevision = &state.Revision
		if step < 3 && !slices.Equal(state.EffectiveDNSServers, request.DNSServers) {
			t.Fatalf("native manual servers = %v", state.EffectiveDNSServers)
		}
		if step == 0 && !slices.Equal(state.EffectiveSearchDomains, []string{"ad.sylve.test"}) {
			t.Fatal("native search override failed")
		}
		if step == 0 {
			// A DHCP refresh runs resolvconf without involving Sylve. Overrides
			// must survive it while DNS-service subscribers still see OS inputs.
			setResolverInput("bridge0", "search changed.lan\nnameserver 192.0.2.99\n")
			if _, err := utils.RunCommandWithContext(t.Context(), script, "-u"); err != nil {
				t.Fatal(err)
			}
			servers, domains := parseGlobalResolver([]byte(readGlobalTestFile(t, runtime.resolverPath)))
			if !slices.Equal(servers, request.DNSServers) || !slices.Equal(domains, request.SearchDomains) {
				t.Fatalf("DHCP refresh replaced manual settings: %v %v", servers, domains)
			}
			setResolverInput("bridge0", "search lan\nnameserver 192.0.2.1\noptions edns0\n")
		}
		if step == 1 && len(state.EffectiveSearchDomains) > 0 {
			t.Fatal("native empty search override failed")
		}
		if (step == 2 || step == 5) && !slices.Equal(state.EffectiveSearchDomains, []string{"lan"}) {
			t.Fatalf("native inherited search = %v", state.EffectiveSearchDomains)
		}
		if step >= 3 && !slices.Equal(state.EffectiveDNSServers, []string{"192.0.2.1", "2001:db8::1"}) {
			t.Fatalf("native OS DNS = %v", state.EffectiveDNSServers)
		}
		if step == 3 && !slices.Equal(state.EffectiveSearchDomains, []string{"lab.test"}) {
			t.Fatal("native search-only override failed")
		}
		if step == 4 && len(state.EffectiveSearchDomains) > 0 {
			t.Fatal("native search-only empty override failed")
		}
		if !strings.Contains(readGlobalTestFile(t, runtime.resolverPath), "# Keep this comment") {
			t.Fatal("native resolver lost unrelated content")
		}
		upstreams, err := utils.RunCommandWithContext(t.Context(), script, "-v")
		if err != nil || !strings.Contains(upstreams, "192.0.2.1") || !strings.Contains(upstreams, "2001:db8::1") || !strings.Contains(upstreams, "lan") || strings.Contains(upstreams, "10.254.0.127") {
			t.Fatalf("host overrides changed DNS-service subscriber inputs: %q %v", upstreams, err)
		}
	}
	if readGlobalTestFile(t, runtime.resolvconfPath) != baseline {
		t.Fatal("native resolver configuration was not released")
	}
	if _, err := os.Stat(unsafePath); !errors.Is(err, os.ErrNotExist) {
		t.Fatal("resolver comment was interpreted as shell code")
	}
}
