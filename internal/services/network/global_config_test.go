func newGlobalConfigServiceForTest(t *testing.T) *Service {
	t.Helper()
	directory := t.TempDir()
	database, err := gorm.Open(sqlite.Open(filepath.Join(directory, "settings.db")), &gorm.Config{})
	if err != nil {
		t.Fatal(err)
	}
	sqlDB, err := database.DB()
	if err != nil {
		t.Fatal(err)
	}
	sqlDB.SetMaxOpenConns(1)
	t.Cleanup(func() { _ = sqlDB.Close() })
	if err := database.AutoMigrate(&networkModels.GlobalConfig{}); err != nil {
		t.Fatal(err)
	}
	service := &Service{DB: database, TelemetryDB: database}
	service.globalConfigRuntime = globalConfigRuntimeOperations{
		resolvconfPath: filepath.Join(directory, "resolvconf.conf"),
		resolverPath:   filepath.Join(directory, "resolv.conf"),
		hostsPath:      filepath.Join(directory, "hosts"),
	}
	runtime := service.globalRuntime()
	writeGlobalTestFile(t, runtime.resolverPath, "# Generated by resolvconf\n# Keep this comment\nsearch lan\nnameserver 192.0.2.1\nnameserver 2001:db8::1\noptions edns0\n")
	writeGlobalTestFile(t, runtime.resolvconfPath, "# Existing configuration\nresolv_conf_options=\"edns0\"\n")
	writeGlobalTestFile(t, runtime.hostsPath, "# Existing hosts\n127.0.0.1 localhost\n::1 localhost\n192.0.2.50 existing.example.com existing\n")
	service.globalConfigRuntime.runCommand = func(ctx context.Context, command string, args ...string) (string, error) {
		if command == "/sbin/route" {
			return "gateway: 192.0.2.1\n", nil
		}
		if command != "/sbin/resolvconf" || !slices.Equal(args, []string{"-u"}) {
			t.Fatalf("unexpected host command: %s %v", command, args)
		}
		if err := ctx.Err(); err != nil {
			return "", err
		}
		configuration, err := os.ReadFile(runtime.resolvconfPath)
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return "", err
		}
		servers, domains := "192.0.2.1 2001:db8::1", "lan"
		for _, line := range strings.Split(string(configuration), "\n") {
			if value, ok := strings.CutPrefix(line, "prepend_nameservers=\""); ok {
				servers = strings.TrimSuffix(value, "\"")
			}
			if value, ok := strings.CutPrefix(line, "prepend_search=\""); ok {
				domains = strings.TrimSuffix(value, "\"")
			}
		}
		previous, _ := os.ReadFile(runtime.resolverPath)
		var resolver strings.Builder
		resolver.WriteString("# Generated by resolvconf\n" + resolverExtras(previous) + "\n")
		if domains != "" {
			resolver.WriteString("search " + domains + "\n")
		}
		for _, server := range strings.Fields(servers) {
			resolver.WriteString("nameserver " + server + "\n")
		}
		return "", os.WriteFile(runtime.resolverPath, []byte(resolver.String()), 0o640)
	}
	return service
}

func writeGlobalTestFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.WriteFile(path, []byte(content), 0o640); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(path, 0o640); err != nil {
		t.Fatal(err)
	}
}

func readGlobalTestFile(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

