func validateFamilyAgainstRawAddress(value string, family string, allowCIDR bool, field string, allowAnyLiteral bool) error {
	v := strings.TrimSpace(value)
	if v == "" {
		return nil
	}

	if allowAnyLiteral && strings.EqualFold(v, "any") {
		return nil
	}

	isV4 := utils.IsValidIPv4(v)
	isV6 := utils.IsValidIPv6(v)
	isV4CIDR := utils.IsValidIPv4CIDR(v)
	isV6CIDR := utils.IsValidIPv6CIDR(v)

	if !(isV4 || isV6 || isV4CIDR || isV6CIDR) {
		return fmt.Errorf("invalid_%s_address: %s", field, v)
	}

	if !allowCIDR && (isV4CIDR || isV6CIDR) {
		return fmt.Errorf("%s_must_be_host_address", field)
	}

	switch family {
	case "inet":
		if isV6 || isV6CIDR {
			return fmt.Errorf("incompatible_family_for_%s: expected_ipv4", field)
		}
	case "inet6":
		if isV4 || isV4CIDR {
			return fmt.Errorf("incompatible_family_for_%s: expected_ipv6", field)
		}
	}

	return nil
}

func validateRawPortSelector(raw string, field string) error {
	trimmed := strings.TrimSpace(raw)
	if trimmed == "" {
		return nil
	}

	if strings.HasPrefix(trimmed, "{") && strings.HasSuffix(trimmed, "}") {
		trimmed = strings.TrimSpace(strings.TrimSuffix(strings.TrimPrefix(trimmed, "{"), "}"))
	}

	tokens := strings.Split(trimmed, ",")
	for _, token := range tokens {
		part := strings.TrimSpace(token)
		if part == "" {
			return fmt.Errorf("invalid_%s_port_selector: empty_token", field)
		}
		if !parsePortValue(part) {
			return fmt.Errorf("invalid_%s_port_selector: %s", field, part)
		}
	}

	return nil
}

func (s *Service) validateFirewallNATTargetObjectRef(id *uint, family, scope, handling, field string, matchFamilies []string) error {
	if id == nil {
		return nil
	}
	if *id == 0 {
		return invalidFirewallNATRule(fmt.Errorf("invalid_%s_object_id", field))
	}

	var object networkModels.Object
	if err := s.DB.Preload("Entries").Select("id,type").First(&object, *id).Error; err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			return invalidFirewallNATRule(fmt.Errorf("%s_object_not_found", field))
		}
		return fmt.Errorf("load %s NAT object: %w", field, err)
	}
	if object.Type == "FQDN" {
		if err := s.DB.Where("object_id = ?", object.ID).Find(&object.Resolutions).Error; err != nil {
			return fmt.Errorf("load %s NAT resolutions: %w", field, err)
		}
		families := []string{family}
		if family == "any" {
			families = matchFamilies
			if len(families) == 1 && families[0] == "any" {
				families = []string{"inet", "inet6"}
			}
		}
		usable := false
		for _, candidate := range families {
			if family == "any" && len(firewallNATTargetValues(&object, candidate, scope)) == 0 {
				continue
			}
			if _, err := firewallNATTargetSelector("", &object, candidate, scope, handling); err != nil {
				return invalidFirewallNATRule(err)
			}
			usable = true
		}
		if !usable {
			return invalidFirewallNATRule(fmt.Errorf("%s_fqdn_has_no_eligible_addresses", field))
		}
		return nil
	}
	if object.Type != "Host" {
		return invalidFirewallNATRule(fmt.Errorf("invalid_%s_object_type", field))
	}
	if len(object.Entries) != 1 {
		return invalidFirewallNATRule(fmt.Errorf("%s_object_requires_single_address", field))
	}
	if scope != "all" || handling != "single" {
		return invalidFirewallNATRule(fmt.Errorf("target_scope_and_pool_require_fqdn_object"))
	}
	if err := validateFamilyAgainstRawAddress(object.Entries[0].Value, family, false, field, false); err != nil {
		return invalidFirewallNATRule(err)
	}

	return nil
}

