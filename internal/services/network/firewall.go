func (s *Service) ensurePFKernelModuleLoaded() error {
	if _, err := firewallRunCommand("/sbin/kldstat", "-m", "pf"); err == nil {
		return nil
	}

	if _, err := firewallRunCommand("/sbin/kldload", "-n", "pf"); err != nil {
		lowered := strings.ToLower(err.Error())
		if strings.Contains(lowered, "already loaded") ||
			strings.Contains(lowered, "in kernel") ||
			strings.Contains(lowered, "file exists") {
			return nil
		}
		return fmt.Errorf("failed_to_load_pf_kernel_module: %w", err)
	}

	return nil
}

