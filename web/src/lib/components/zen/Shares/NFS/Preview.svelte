<script lang="ts">
	import { getNFSPreview } from '$lib/api/nfs';
	import { Button } from '$lib/components/ui/button/index.js';
	import * as Dialog from '$lib/components/ui/dialog/index.js';
	import { ScrollArea } from '$lib/components/ui/scroll-area/index.js';
	import type { NFSPreview } from '$lib/types/nfs';
	import { isAPIResponse } from '$lib/utils/http';
	import { onDestroy } from 'svelte';
	import { planError } from './nfs';

	let { hostname, onClose }: { hostname: string; onClose: () => void } = $props();

	const KNOWN_WARNINGS = new Set([
		'Preview only: no host changes were made.',
		'AUTH_SYS trusts client-supplied numeric identities; filesystem permissions are not changed.',
		'No shares are enabled.'
	]);
	const lifetime = new AbortController();
	let preview = $state<NFSPreview | null>(null);
	let error = $state('');
	let loading = $state(true);
	let content = $derived(
		(preview?.exports ?? '')
			.split('\n')
			.filter((line) => !line.startsWith('# === This file is automatically generated by Sylve'))
			.join('\n')
			.trim()
	);
	let warnings = $derived(
		(preview?.warnings ?? []).filter((warning) => !KNOWN_WARNINGS.has(warning))
	);

	async function load() {
		loading = true;
		error = '';
		const result = await getNFSPreview({ hostname, signal: lifetime.signal }).catch(() => null);
		if (lifetime.signal.aborted) return;
		loading = false;
		if (!result) error = 'The exports couldn’t be generated.';
		else if (isAPIResponse(result)) error = planError(result, 'The exports couldn’t be generated.');
		else preview = result;
	}

	void load();
	onDestroy(() => lifetime.abort());
</script>

<Dialog.Root
	open
	onOpenChange={(open) => {
		if (!open) onClose();
	}}
>
	<Dialog.Content
		class="flex max-h-[calc(100dvh-2rem)] flex-col gap-0 overflow-hidden p-0 sm:max-w-3xl"
		showCloseButton={false}
	>
		<div class="flex shrink-0 items-center justify-between gap-3 border-b px-4 pt-4 pb-3">
			<Dialog.Header class="min-w-0 text-left">
				<Dialog.Title class="flex min-h-9 items-center gap-2.5 text-base leading-snug">
					<span
						class="icon-[lucide--file-search] text-zen-highlight-foreground size-5 shrink-0"
						aria-hidden="true"
					></span>
					Exports Preview
				</Dialog.Title>
				<Dialog.Description class="sr-only">
					The exports file the saved NFS settings and shares produce.
				</Dialog.Description>
			</Dialog.Header>
			<Dialog.Close>
				{#snippet child({ props })}
					<Button {...props} variant="ghost" size="icon" class="size-9 shrink-0">
						<span class="icon-[lucide--x] size-5" aria-hidden="true"></span>
						<span class="sr-only">Close</span>
					</Button>
				{/snippet}
			</Dialog.Close>
		</div>
		<div class="min-h-0 flex-1 space-y-3 p-4">
			{#if loading}
				<p class="text-muted-foreground flex items-center gap-2 text-sm">
					<span class="icon-[lucide--loader-circle] size-4 animate-spin" aria-hidden="true"></span>
					Generating exports…
				</p>
			{:else if error}
				<div class="flex flex-wrap items-center gap-3 text-sm" role="alert">
					<p class="text-destructive min-w-0 flex-1 break-words">{error}</p>
					<Button variant="outline" size="sm" onclick={() => void load()}>Try Again</Button>
				</div>
			{:else if preview}
				<p class="text-muted-foreground text-sm">
					What Sylve writes to /etc/exports for the saved settings and shares. It may not be applied
					yet.
				</p>
				{#if warnings.length}
					<ul class="space-y-1 text-sm text-amber-600 dark:text-amber-400">
						{#each warnings as warning (warning)}
							<li class="flex items-start gap-2">
								<span
									class="icon-[lucide--triangle-alert] mt-0.5 size-4 shrink-0"
									aria-hidden="true"
								></span>
								{warning}
							</li>
						{/each}
					</ul>
				{/if}
				<ScrollArea
					class="bg-muted/40 rounded-md border"
					fade
					scrollbarYClasses="hidden"
					viewportProps={{
						class: 'max-h-96 overscroll-contain',
						role: 'region',
						'aria-label': 'Exports',
						tabindex: 0
					}}
				>
					<pre
						class="p-3 font-mono text-xs leading-relaxed whitespace-pre-wrap break-all">{content ||
							'Nothing is exported.'}</pre>
				</ScrollArea>
			{/if}
		</div>
	</Dialog.Content>
</Dialog.Root>
